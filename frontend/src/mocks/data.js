export function seedCommentsFor(post) {
  const base = Date.parse(post.createdAt);
  return pool.slice(0, post.comments).map((c, i) => ({
    id: `${post.id}-seed-${i}`,
    postId: post.id,
    author: { id: `seed-${c.username}`, username: c.username, displayName: c.displayName, color: c.color },
    text: c.text,
    createdAt: new Date(Math.min(Date.now() - 1000, base + (i + 1) * 25 * 60000)).toISOString(),
  }));
}
